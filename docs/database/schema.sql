-- Intern : modèle physique de référence, PostgreSQL 16.
-- Ne constitue PAS une migration Django. Crée uniquement intern_blueprint.
-- Précondition : public.auth_user existe (authentification Django actuelle).
-- Exécuter dans une transaction sur une base de développement, puis ROLLBACK.
-- Pas de IF NOT EXISTS : un schéma préexistant doit provoquer un échec.
CREATE SCHEMA intern_blueprint;
SET LOCAL search_path TO intern_blueprint, public;

CREATE TABLE location (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 canonical_key varchar(240) NOT NULL UNIQUE,
 label varchar(240) NOT NULL,
 country_code varchar(2), region varchar(160), city varchar(160),
 CHECK (country_code IS NULL OR country_code ~ '^[A-Z]{2}$')
);
CREATE TABLE role (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug varchar(140) NOT NULL UNIQUE, name varchar(160) NOT NULL
);
CREATE TABLE skill (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug varchar(140) NOT NULL UNIQUE, name varchar(160) NOT NULL
);
CREATE TABLE company (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(240) NOT NULL, website_url text, domain varchar(253),
 description text NOT NULL DEFAULT '', logo_object_key text,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX company_domain_idx ON company(domain);
CREATE TABLE offer (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id bigint NOT NULL REFERENCES company ON DELETE RESTRICT,
 role_id bigint REFERENCES role ON DELETE RESTRICT,
 title varchar(300) NOT NULL, description_text text NOT NULL,
 contract_type varchar(24) NOT NULL DEFAULT 'unknown'
   CHECK (contract_type IN ('internship','apprenticeship','employment','contractor','temporary','unknown')),
 employment_schedule varchar(12) NOT NULL DEFAULT 'unknown'
   CHECK (employment_schedule IN ('full_time','part_time','unknown')),
 work_mode varchar(12) NOT NULL DEFAULT 'unknown'
   CHECK (work_mode IN ('remote','hybrid','onsite','unknown')),
 seniority varchar(16) NOT NULL DEFAULT 'unknown'
   CHECK (seniority IN ('entry','mid','senior','lead','executive','unknown')),
 remote_scope text, language_code varchar(16),
 status varchar(12) NOT NULL DEFAULT 'open' CHECK (status IN ('open','closed','expired','hidden')),
 published_at timestamptz, expires_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 search_vector tsvector GENERATED ALWAYS AS (
   setweight(to_tsvector('simple'::regconfig, coalesce(title,'')), 'A') ||
   setweight(to_tsvector('simple'::regconfig, coalesce(description_text,'')), 'B')
 ) STORED,
 CHECK (expires_at IS NULL OR published_at IS NULL OR expires_at >= published_at)
);
CREATE TABLE offer_location (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 offer_id bigint NOT NULL REFERENCES offer ON DELETE CASCADE,
 location_id bigint NOT NULL REFERENCES location ON DELETE RESTRICT,
 UNIQUE(offer_id,location_id)
);
CREATE INDEX offer_location_reverse_idx ON offer_location(location_id,offer_id);
CREATE TABLE offer_skill (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 offer_id bigint NOT NULL REFERENCES offer ON DELETE CASCADE,
 skill_id bigint NOT NULL REFERENCES skill ON DELETE RESTRICT,
 importance varchar(12) NOT NULL DEFAULT 'unspecified'
   CHECK (importance IN ('required','preferred','unspecified')),
 UNIQUE(offer_id,skill_id)
);
CREATE INDEX offer_skill_reverse_idx ON offer_skill(skill_id,offer_id);
CREATE TABLE source_board (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 provider varchar(40) NOT NULL, instance varchar(40) NOT NULL DEFAULT 'global',
 board_key varchar(240) NOT NULL,
 company_id bigint REFERENCES company ON DELETE RESTRICT,
 base_url text NOT NULL, enabled boolean NOT NULL DEFAULT true,
 submission_mode varchar(16) NOT NULL DEFAULT 'unsupported'
   CHECK (submission_mode IN ('browser','partner_api','unsupported')),
 adapter_version varchar(80), last_success_at timestamptz,
 UNIQUE(provider,instance,board_key)
);
CREATE TABLE import_run (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 board_id bigint NOT NULL REFERENCES source_board ON DELETE RESTRICT,
 status varchar(12) NOT NULL CHECK (status IN ('running','succeeded','failed')),
 started_at timestamptz NOT NULL DEFAULT now(), finished_at timestamptz,
 is_full_snapshot boolean NOT NULL DEFAULT false,
 seen_count integer NOT NULL DEFAULT 0 CHECK (seen_count >= 0),
 error_code varchar(80), UNIQUE(id,board_id),
 CHECK (finished_at IS NULL OR finished_at >= started_at)
);
CREATE TABLE offer_source (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 offer_id bigint NOT NULL REFERENCES offer ON DELETE RESTRICT,
 board_id bigint NOT NULL REFERENCES source_board ON DELETE RESTRICT,
 external_id varchar(300) NOT NULL, external_requisition_id varchar(300),
 origin_url text NOT NULL, apply_url text NOT NULL,
 source_status varchar(12) NOT NULL DEFAULT 'active'
   CHECK (source_status IN ('active','missing','closed','unknown')),
 first_seen_at timestamptz NOT NULL DEFAULT now(), last_seen_at timestamptz NOT NULL DEFAULT now(),
 last_checked_at timestamptz, last_seen_run_id bigint,
 content_hash varchar(64) NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),
 raw_payload jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(raw_payload) = 'object'),
 raw_expires_at timestamptz,
 UNIQUE(board_id,external_id), UNIQUE(id,offer_id),
 FOREIGN KEY(last_seen_run_id,board_id) REFERENCES import_run(id,board_id) ON DELETE RESTRICT,
 CHECK (last_seen_at >= first_seen_at)
);
CREATE INDEX offer_source_offer_idx ON offer_source(offer_id);
CREATE TABLE compensation_band (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 offer_id bigint NOT NULL REFERENCES offer ON DELETE CASCADE,
 source_id bigint NOT NULL,
 location_id bigint REFERENCES location ON DELETE RESTRICT,
 label varchar(240), minimum numeric(16,2), maximum numeric(16,2),
 currency varchar(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
 period varchar(10) NOT NULL CHECK (period IN ('hour','day','week','month','year')),
 gross_net varchar(10) NOT NULL DEFAULT 'unknown' CHECK (gross_net IN ('gross','net','unknown')),
 FOREIGN KEY(source_id,offer_id) REFERENCES offer_source(id,offer_id) ON DELETE RESTRICT,
 CHECK (minimum IS NOT NULL OR maximum IS NOT NULL),
 CHECK (minimum IS NULL OR minimum >= 0), CHECK (maximum IS NULL OR maximum >= 0),
 CHECK (minimum IS NULL OR maximum IS NULL OR maximum >= minimum)
);
CREATE INDEX compensation_offer_idx ON compensation_band(offer_id);
CREATE INDEX offer_feed_idx ON offer(published_at DESC NULLS LAST,id DESC) WHERE status='open';
CREATE INDEX offer_filters_idx ON offer(contract_type,work_mode,published_at DESC) WHERE status='open';
CREATE INDEX offer_company_idx ON offer(company_id);
CREATE INDEX offer_role_idx ON offer(role_id);
CREATE INDEX offer_search_idx ON offer USING gin(search_vector);

CREATE TABLE document (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id integer NOT NULL REFERENCES public.auth_user(id) ON DELETE RESTRICT,
 kind varchar(16) NOT NULL CHECK (kind IN ('resume','cover_letter','evidence')),
 origin varchar(12) NOT NULL CHECK (origin IN ('upload','generated','capture')),
 bucket varchar(100) NOT NULL, object_key text NOT NULL,
 original_name varchar(255), mime_type varchar(160) NOT NULL,
 byte_size bigint NOT NULL CHECK (byte_size > 0),
 sha256 varchar(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
 status varchar(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','ready','quarantined','deleting')),
 derived_from_id bigint, created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(bucket,object_key), UNIQUE(id,owner_id), UNIQUE(id,owner_id,kind),
 FOREIGN KEY(derived_from_id,owner_id) REFERENCES document(id,owner_id) ON DELETE RESTRICT,
 CHECK (derived_from_id IS NULL OR derived_from_id <> id)
);
CREATE INDEX document_owner_idx ON document(owner_id,created_at DESC);
CREATE TABLE candidate_profile (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id integer NOT NULL UNIQUE REFERENCES public.auth_user(id) ON DELETE RESTRICT,
 full_name varchar(240) NOT NULL, first_name varchar(160), last_name varchar(160),
 phone varchar(40), headline varchar(300), summary text,
 location_id bigint REFERENCES location ON DELETE RESTRICT,
 location_text varchar(240), available_from date,
 linkedin_url text, github_url text, portfolio_url text,
 current_resume_id bigint,
 current_resume_kind varchar(16) NOT NULL DEFAULT 'resume' CHECK(current_resume_kind='resume'),
 profile_version integer NOT NULL DEFAULT 1 CHECK(profile_version > 0),
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(current_resume_id,user_id,current_resume_kind)
   REFERENCES document(id,owner_id,kind) ON DELETE RESTRICT
);
CREATE TABLE experience (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 profile_id bigint NOT NULL REFERENCES candidate_profile ON DELETE CASCADE,
 company_name varchar(240) NOT NULL, title varchar(240) NOT NULL,
 start_date date, end_date date, is_current boolean NOT NULL DEFAULT false,
 date_precision varchar(8) NOT NULL DEFAULT 'month' CHECK(date_precision IN ('day','month','year')),
 description text NOT NULL DEFAULT '', position integer NOT NULL DEFAULT 0,
 CHECK(end_date IS NULL OR start_date IS NULL OR end_date >= start_date),
 CHECK(NOT is_current OR end_date IS NULL)
);
CREATE TABLE education (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 profile_id bigint NOT NULL REFERENCES candidate_profile ON DELETE CASCADE,
 institution varchar(240) NOT NULL, degree varchar(240), field_of_study varchar(240),
 start_date date, end_date date, is_current boolean NOT NULL DEFAULT false,
 date_precision varchar(8) NOT NULL DEFAULT 'month' CHECK(date_precision IN ('day','month','year')),
 description text NOT NULL DEFAULT '', position integer NOT NULL DEFAULT 0,
 CHECK(end_date IS NULL OR start_date IS NULL OR end_date >= start_date),
 CHECK(NOT is_current OR end_date IS NULL)
);
CREATE TABLE project (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 profile_id bigint NOT NULL REFERENCES candidate_profile ON DELETE CASCADE,
 title varchar(240) NOT NULL, description text NOT NULL DEFAULT '', url text,
 position integer NOT NULL DEFAULT 0
);
CREATE TABLE candidate_skill (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 profile_id bigint NOT NULL REFERENCES candidate_profile ON DELETE CASCADE,
 skill_id bigint NOT NULL REFERENCES skill ON DELETE RESTRICT,
 UNIQUE(profile_id,skill_id)
);
CREATE TABLE work_authorization (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 profile_id bigint NOT NULL REFERENCES candidate_profile ON DELETE CASCADE,
 country_code varchar(2) NOT NULL CHECK(country_code ~ '^[A-Z]{2}$'),
 authorized boolean, needs_sponsorship boolean, confirmed_at timestamptz,
 UNIQUE(profile_id,country_code)
);
CREATE TABLE search_preference (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 profile_id bigint NOT NULL UNIQUE REFERENCES candidate_profile ON DELETE CASCADE,
 minimum_salary numeric(16,2), salary_currency varchar(3), salary_period varchar(10),
 salary_gross_net varchar(5) NOT NULL DEFAULT 'gross' CHECK(salary_gross_net IN ('gross','net')),
 willing_to_relocate boolean, updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK ((minimum_salary IS NULL AND salary_currency IS NULL AND salary_period IS NULL) OR
   (minimum_salary IS NOT NULL AND minimum_salary >= 0 AND salary_currency IS NOT NULL AND
    salary_currency ~ '^[A-Z]{3}$' AND salary_period IS NOT NULL AND
    salary_period IN ('hour','day','week','month','year')))
);
CREATE TABLE preference_role (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 preference_id bigint NOT NULL REFERENCES search_preference ON DELETE CASCADE,
 role_id bigint NOT NULL REFERENCES role ON DELETE RESTRICT, UNIQUE(preference_id,role_id)
);
CREATE TABLE preference_location (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 preference_id bigint NOT NULL REFERENCES search_preference ON DELETE CASCADE,
 location_id bigint NOT NULL REFERENCES location ON DELETE RESTRICT, UNIQUE(preference_id,location_id)
);
CREATE TABLE preference_contract (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 preference_id bigint NOT NULL REFERENCES search_preference ON DELETE CASCADE,
 value varchar(24) NOT NULL CHECK(value IN ('internship','apprenticeship','employment','contractor','temporary')),
 UNIQUE(preference_id,value)
);
CREATE TABLE preference_work_mode (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 preference_id bigint NOT NULL REFERENCES search_preference ON DELETE CASCADE,
 value varchar(12) NOT NULL CHECK(value IN ('remote','hybrid','onsite')),
 UNIQUE(preference_id,value)
);
CREATE TABLE saved_offer (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id integer NOT NULL REFERENCES public.auth_user(id) ON DELETE CASCADE,
 offer_id bigint NOT NULL REFERENCES offer ON DELETE CASCADE,
 created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(user_id,offer_id)
);
CREATE INDEX saved_offer_feed_idx ON saved_offer(user_id,created_at DESC,id DESC);

CREATE TABLE application (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id integer NOT NULL REFERENCES public.auth_user(id) ON DELETE RESTRICT,
 offer_id bigint NOT NULL REFERENCES offer ON DELETE RESTRICT,
 source_id bigint NOT NULL,
 status varchar(16) NOT NULL DEFAULT 'draft'
   CHECK(status IN ('draft','submitted','screening','interview','offer_received','accepted','rejected','withdrawn')),
 submitted_at timestamptz, external_reference varchar(300),
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(user_id,offer_id), UNIQUE(id,user_id),
 FOREIGN KEY(source_id,offer_id) REFERENCES offer_source(id,offer_id) ON DELETE RESTRICT
);
CREATE TABLE application_revision (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id bigint NOT NULL, user_id integer NOT NULL,
 revision_no integer NOT NULL CHECK(revision_no > 0),
 schema_version integer NOT NULL DEFAULT 1 CHECK(schema_version > 0),
 profile_snapshot jsonb NOT NULL CHECK(jsonb_typeof(profile_snapshot)='object'),
 offer_snapshot jsonb NOT NULL CHECK(jsonb_typeof(offer_snapshot)='object'),
 form_snapshot jsonb NOT NULL CHECK(jsonb_typeof(form_snapshot)='object'),
 answers jsonb NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(answers)='array'),
 generator_version varchar(120), prompt_version varchar(120),
 content_hash varchar(64) CHECK(content_hash ~ '^[0-9a-f]{64}$'),
 sealed_at timestamptz, created_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(application_id,user_id) REFERENCES application(id,user_id) ON DELETE RESTRICT,
 UNIQUE(application_id,revision_no), UNIQUE(id,user_id), UNIQUE(id,application_id,user_id),
 CHECK(sealed_at IS NULL OR content_hash IS NOT NULL)
);
CREATE TABLE revision_document (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 revision_id bigint NOT NULL, user_id integer NOT NULL, document_id bigint NOT NULL,
 purpose varchar(16) NOT NULL CHECK(purpose IN ('resume','cover_letter')),
 FOREIGN KEY(revision_id,user_id) REFERENCES application_revision(id,user_id) ON DELETE CASCADE,
 FOREIGN KEY(document_id,user_id,purpose) REFERENCES document(id,owner_id,kind) ON DELETE RESTRICT,
 UNIQUE(revision_id,purpose)
);
CREATE TABLE submission_authorization (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 revision_id bigint NOT NULL, application_id bigint NOT NULL, user_id integer NOT NULL,
 approved_hash varchar(64) NOT NULL CHECK(approved_hash ~ '^[0-9a-f]{64}$'),
 mode varchar(16) NOT NULL DEFAULT 'per_application' CHECK(mode='per_application'),
 granted_at timestamptz NOT NULL DEFAULT now(), expires_at timestamptz NOT NULL,
 revoked_at timestamptz,
 FOREIGN KEY(revision_id,application_id,user_id) REFERENCES application_revision(id,application_id,user_id) ON DELETE RESTRICT,
 UNIQUE(id,revision_id,application_id,user_id),
 CHECK(expires_at > granted_at), CHECK(revoked_at IS NULL OR revoked_at >= granted_at)
);
CREATE UNIQUE INDEX one_unrevoked_authorization_idx ON submission_authorization(revision_id) WHERE revoked_at IS NULL;
CREATE TABLE agent_run (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id bigint NOT NULL, user_id integer NOT NULL, revision_id bigint NOT NULL,
 authorization_id bigint, purpose varchar(12) NOT NULL CHECK(purpose IN ('prepare','submit')),
 status varchar(16) NOT NULL DEFAULT 'queued'
   CHECK(status IN ('queued','running','needs_input','uncertain','succeeded','failed','cancelled')),
 phase varchar(16) NOT NULL DEFAULT 'preparing'
   CHECK(phase IN ('preparing','filling','awaiting_user','submitting','verifying','done')),
 idempotency_key uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
 worker_token uuid, lease_expires_at timestamptz, heartbeat_at timestamptz,
 attempt_no integer NOT NULL CHECK(attempt_no > 0),
 adapter_version varchar(120), error_code varchar(80),
 evidence_document_id bigint, external_receipt varchar(300),
 started_at timestamptz, finished_at timestamptz, created_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(revision_id,application_id,user_id) REFERENCES application_revision(id,application_id,user_id) ON DELETE RESTRICT,
 FOREIGN KEY(authorization_id,revision_id,application_id,user_id)
   REFERENCES submission_authorization(id,revision_id,application_id,user_id) ON DELETE RESTRICT,
 FOREIGN KEY(evidence_document_id,user_id) REFERENCES document(id,owner_id) ON DELETE RESTRICT,
 UNIQUE(application_id,attempt_no), UNIQUE(id,application_id),
 CHECK(purpose <> 'submit' OR authorization_id IS NOT NULL),
 CHECK(finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at)
);
-- Une incertitude bloque aussi une nouvelle tentative jusqu'à réconciliation.
CREATE UNIQUE INDEX one_active_run_idx ON agent_run(application_id)
 WHERE status IN ('queued','running','needs_input','uncertain');
CREATE INDEX agent_queue_idx ON agent_run(created_at,id) WHERE status='queued';
CREATE TABLE application_event (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id bigint NOT NULL REFERENCES application ON DELETE RESTRICT,
 run_id bigint, kind varchar(80) NOT NULL,
 origin varchar(16) NOT NULL CHECK(origin IN ('user','agent','system','provider')),
 status_after varchar(16) CHECK(status_after IN ('draft','submitted','screening','interview','offer_received','accepted','rejected','withdrawn')),
 happened_at timestamptz NOT NULL, recorded_at timestamptz NOT NULL DEFAULT now(),
 dedupe_key varchar(300), payload jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(payload)='object'),
 FOREIGN KEY(run_id,application_id) REFERENCES agent_run(id,application_id) ON DELETE RESTRICT,
 UNIQUE(application_id,origin,dedupe_key)
);
CREATE TABLE interview (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id bigint NOT NULL REFERENCES application ON DELETE CASCADE,
 title varchar(240) NOT NULL, starts_at timestamptz NOT NULL, ends_at timestamptz,
 display_timezone varchar(80) NOT NULL DEFAULT 'UTC', meeting_url text, location_text text,
 status varchar(12) NOT NULL DEFAULT 'scheduled' CHECK(status IN ('scheduled','completed','cancelled')),
 notes text NOT NULL DEFAULT '', CHECK(ends_at IS NULL OR ends_at >= starts_at)
);
CREATE TABLE application_task (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id bigint NOT NULL REFERENCES application ON DELETE CASCADE,
 title varchar(240) NOT NULL, due_at timestamptz, completed_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX application_tracker_idx ON application(user_id,status,updated_at DESC,id DESC);
CREATE INDEX application_offer_idx ON application(offer_id);
CREATE INDEX application_events_idx ON application_event(application_id,happened_at,id);
CREATE INDEX interview_application_idx ON interview(application_id,starts_at);
CREATE INDEX application_task_due_idx ON application_task(application_id,due_at) WHERE completed_at IS NULL;

CREATE TABLE outbox_message (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 topic varchar(80) NOT NULL, dedupe_key varchar(300) NOT NULL UNIQUE,
 owner_id integer REFERENCES public.auth_user(id) ON DELETE RESTRICT,
 payload jsonb NOT NULL CHECK(jsonb_typeof(payload)='object'),
 available_at timestamptz NOT NULL DEFAULT now(), processed_at timestamptz,
 attempts integer NOT NULL DEFAULT 0 CHECK(attempts>=0),
 lease_token uuid, lease_expires_at timestamptz, last_error_code varchar(80),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX outbox_pending_idx ON outbox_message(available_at,id) WHERE processed_at IS NULL;
CREATE TABLE deletion_request (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id integer UNIQUE REFERENCES public.auth_user(id) ON DELETE SET NULL,
 status varchar(16) NOT NULL DEFAULT 'requested' CHECK(status IN ('requested','running','completed','failed')),
 requested_at timestamptz NOT NULL DEFAULT now(), completed_at timestamptz,
 last_error_code varchar(80), CHECK(completed_at IS NULL OR completed_at>=requested_at)
);
-- Index des enfants profil pour lectures et suppression (Django les crée sur ses FK).
CREATE INDEX experience_profile_idx ON experience(profile_id);
CREATE INDEX education_profile_idx ON education(profile_id);
CREATE INDEX project_profile_idx ON project(profile_id);
-- Les autres FK composites ont des index ciblés ici ; les UNIQUE couvrent les préfixes.
CREATE INDEX source_board_company_idx ON source_board(company_id);
CREATE INDEX import_run_board_idx ON import_run(board_id,started_at DESC);
CREATE INDEX authorization_revision_idx ON submission_authorization(revision_id);
CREATE INDEX revision_document_document_idx ON revision_document(document_id);
CREATE INDEX agent_run_authorization_idx ON agent_run(authorization_id);
CREATE INDEX outbox_owner_idx ON outbox_message(owner_id);
