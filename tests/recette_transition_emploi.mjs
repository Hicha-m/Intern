// Real browser/API/PostgreSQL acceptance after the historical replay fixture.
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
const require = createRequire(new URL('../frontend/package.json', import.meta.url))
const { chromium } = require('@playwright/test')
if (!process.env.RECETTE_PASSWORD || !process.env.RECETTE_TRANSITION_MANIFEST) throw new Error('Set RECETTE_PASSWORD and RECETTE_TRANSITION_MANIFEST.')
const fixture = JSON.parse(await readFile(process.env.RECETTE_TRANSITION_MANIFEST, 'utf8'))
const browser = await chromium.launch({ channel: 'chrome', headless: true })
try {
  const context = await browser.newContext({ baseURL: process.env.RECETTE_URL || 'http://127.0.0.1:5173' })
  const page = await context.newPage()
  await page.goto('/login')
  await page.getByLabel('Adresse e-mail').fill('alice@example.test')
  await page.getByLabel('Mot de passe', { exact: true }).fill(process.env.RECETTE_PASSWORD)
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await page.waitForURL(/\/dashboard$/)
  const company = await (await context.request.get(`/api/v1/companies/${fixture.company_id}/`)).json()
  const query = encodeURIComponent(company.name)
  await page.goto(`/stages?q=${query}`)
  await page.getByRole('heading', { name: 'Emplois informatiques en Europe', exact: true }).waitFor()
  await page.locator('.catalogue-card').first().waitFor()
  assert.equal(await page.locator('.catalogue-card').count(), 8)
  console.log('PASS retained /stages URL displays eight IT contracts after historical replay')
  await page.goto(`/companies/${fixture.company_id}`)
  await page.getByRole('heading', { name: /^Les offres chez/ }).waitFor()
  for (const item of fixture.cases.filter(item => item.label !== 'outside-it')) {
    const response = await context.request.get(`/api/v1/offers/${item.id}/`)
    assert.equal(response.status(), 200)
    const offer = await response.json()
    assert.equal(offer.contract_type, item.contract)
    assert.equal(offer.seniority, item.seniority)
    assert.ok(offer.facts.duration.source_revision_id)
    const card = page.locator('.company-offer-card').filter({ hasText: item.title })
    assert.ok((await card.locator('.company-offer-type').textContent()).includes(item.label))
  }
  console.log('PASS eight historical contracts/levels and source evidence in company cards/API')
  assert.equal((await context.request.get(`/api/v1/offers/${fixture.cases.at(-1).id}/`)).status(), 404)
  console.log('PASS historical non-IT internship excluded')
  const generic = fixture.cases.find(item => item.contract === 'employment')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('.company-offer-card').filter({ hasText: generic.title }).getByRole('link').click()
  await page.getByRole('heading', { name: generic.title, exact: true }).waitFor()
  await page.getByRole('heading', { name: 'À propos du poste', exact: true }).waitFor()
  assert.ok((await page.locator('.offer-detail-tags').textContent()).includes('Niveau non précisé'))
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  await page.getByRole('link', { name: 'Retour à l’entreprise', exact: true }).click()
  await page.getByRole('heading', { name: /^Les offres chez/ }).waitFor()
  console.log('PASS generic contract mobile detail, unknown seniority and preserved company navigation')
  assert.equal((await context.request.get(`/api/v1/applications/${fixture.application_id}/`)).status(), 200)
  console.log('PASS historical application still accessible to its owner')
  await page.goto(`/stages?q=${query}&contract_type=internship`)
  await page.locator('.catalogue-card').first().waitFor()
  assert.equal(await page.locator('.catalogue-card').count(), 1)
  console.log('PASS explicit internship filter preserved')
  console.log('Historical employment acceptance: 6 checks passed on real Chrome/API/PostgreSQL; fictitious data only.')
} finally {
  await browser.close()
}
