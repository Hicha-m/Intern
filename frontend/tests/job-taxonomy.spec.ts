import { expect, test } from '@playwright/test'
import { prepareDashboard } from './fixtures/dashboard'
import { prepareTaxonomy } from './fixtures/taxonomy'

test('specialties search aliases, multi-select, preserve filters and reset pagination', async ({ page }) => {
  const requests = await prepareDashboard(page)
  await prepareTaxonomy(page)
  await page.goto('/stages?q=intern&country_codes=FR&page=3')
  const picker = page.getByRole('button', { name: 'Domaines et métiers', exact: true })
  await picker.click()
  const dialog = page.getByRole('dialog', { name: 'Domaines et métiers' })
  const search = dialog.getByRole('searchbox', { name: 'Rechercher un métier' })
  await expect(search).toBeFocused()
  await search.fill('développement serveur')
  await dialog.getByRole('checkbox', { name: 'Backend', exact: false }).check()
  await search.fill('frontend')
  await dialog.getByRole('checkbox', { name: 'Frontend', exact: false }).check()
  await dialog.getByRole('button', { name: 'Voir les offres' }).click()
  await expect(page).toHaveURL(/subdomains=backend%2Cfrontend/)
  await expect(page).toHaveURL(/country_codes=FR/)
  await expect(page).not.toHaveURL(/page=/)
  await expect.poll(() => requests.filter(url => url.pathname.endsWith('/offers/')).at(-1)?.searchParams.get('subdomains')).toBe('backend,frontend')
  await expect(picker).toBeFocused()
  await page.reload()
  await expect(picker).toContainText('2 sélections')
  await page.getByRole('button', { name: 'Retirer Métier : Backend' }).click()
  await expect(page).toHaveURL(/subdomains=frontend/)
  await page.goBack()
  await expect(picker).toContainText('2 sélections')
})

test('parent selection, partial state, zero counts, cancel, keyboard and mobile layout', async ({ page }, info) => {
  await prepareDashboard(page)
  await prepareTaxonomy(page)
  await page.goto('/stages')
  const picker = page.getByRole('button', { name: 'Domaines et métiers', exact: true })
  await picker.focus()
  await picker.press('Enter')
  const dialog = page.getByRole('dialog')
  await dialog.locator('summary').filter({ hasText: 'Informatique et systèmes' }).click()
  const group = dialog.locator('details').filter({ hasText: 'Informatique et systèmes' })
  await expect(group.getByRole('checkbox', { name: 'Mobile', exact: false })).toBeDisabled()
  await group.getByRole('checkbox', { name: 'Tout le domaine', exact: false }).check()
  await expect(group.getByRole('checkbox', { name: 'Backend', exact: false })).toBeChecked()
  await group.getByRole('checkbox', { name: 'Backend', exact: false }).uncheck()
  await expect(group.getByRole('checkbox', { name: 'Tout le domaine', exact: false })).toHaveJSProperty('indeterminate', true)
  await dialog.getByRole('button', { name: 'Annuler', exact: true }).click()
  await expect(picker).toHaveText('Tous les domaines⌄')
  await expect(picker).toBeFocused()
  await picker.click()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(picker).toBeFocused()
  await page.setViewportSize({ width: 320, height: 740 })
  await picker.click()
  await dialog.getByRole('searchbox').fill('backend')
  await dialog.getByRole('checkbox', { name: 'Backend', exact: false }).check()
  await page.screenshot({ path: info.outputPath('job-taxonomy-mobile.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const box = await dialog.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(320)
  await dialog.getByRole('button', { name: 'Voir les offres' }).click()
  await expect(page).toHaveURL(/subdomains=backend/)
})

test('taxonomy failure leaves search usable and the picker can retry', async ({ page }) => {
  await prepareDashboard(page)
  let failed = true
  await page.route('**/api/v1/taxonomy/**', route => failed ? route.fulfill({ status: 503 }) : route.fulfill({ json: { version: 'v1', domains: [] } }))
  await page.goto('/stages')
  await page.getByRole('button', { name: 'Domaines et métiers', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Impossible de charger les métiers')
  failed = false
  await page.getByRole('button', { name: 'Réessayer', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('button', { name: 'Fermer les métiers' }).click()
  const search = page.getByRole('searchbox', { name: 'Rechercher un emploi' })
  await search.fill('Python')
  await search.press('Enter')
  await expect(page).toHaveURL(/q=Python/)
})

test('profile saves specialties and exclusions without dropping contract preferences', async ({ page }) => {
  await prepareDashboard(page)
  await prepareTaxonomy(page)
  let preferences = { domains: [] as string[], subdomains: [] as string[], excluded_subdomains: [] as string[], role_ids: [], location_ids: [], contracts: ['internship'], work_modes: ['onsite'], minimum_salary: null, salary_currency: null, salary_period: null, salary_gross_net: 'gross', willing_to_relocate: null }
  let saved: Record<string, unknown> = {}
  await page.route('**/api/v1/profile/', route => route.fulfill({ json: { id: 1, full_name: 'Alex Morgan', first_name: 'Alex', last_name: 'Morgan', skill_ids: [], current_resume_id: null } }))
  await page.route('**/api/v1/auth/csrf/', route => route.fulfill({ json: { csrf_token: 'taxonomy-test' } }))
  await page.route('**/api/v1/preferences/', route => {
    if (route.request().method() === 'PUT') { saved = route.request().postDataJSON(); preferences = { ...preferences, ...saved } }
    return route.fulfill({ json: preferences })
  })
  await page.goto('/profil#preferences')
  await page.getByRole('button', { name: 'Modifier Préférences de recherche' }).click()
  await page.getByRole('button', { name: 'Domaines et métiers', exact: true }).click()
  await page.getByRole('dialog').getByRole('searchbox').fill('backend')
  await page.getByRole('checkbox', { name: 'Backend', exact: false }).check()
  await page.getByRole('button', { name: 'Choisir ces métiers' }).click()
  await page.getByRole('button', { name: 'Métiers à exclure', exact: true }).click()
  await page.getByRole('dialog').getByRole('searchbox').fill('frontend')
  await page.getByRole('checkbox', { name: 'Frontend', exact: false }).check()
  await page.getByRole('button', { name: 'Choisir ces métiers' }).click()
  await page.locator('#preferences').getByRole('button', { name: 'Enregistrer', exact: true }).click()
  await expect.poll(() => saved.subdomains).toEqual(['backend'])
  expect(saved.excluded_subdomains).toEqual(['frontend'])
  expect(saved.contracts).toEqual(['internship'])
  expect(saved.work_modes).toEqual(['onsite'])
  await expect(page.locator('#preferences')).toContainText('Backend')
  await expect(page.locator('#preferences')).toContainText('Frontend')
})
