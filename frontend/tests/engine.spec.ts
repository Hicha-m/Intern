async function prepareEngine(page: Page) {
  await prepareDashboard(page)
  await prepareTaxonomy(page)
  const requests: { path: string; method: string; body: any }[] = []
  let searches: any[] = [], external: any[] = [], read = false
  await page.route('**/api/v1/coverage/', route => route.fulfill({ json: { active_sources: 3, verified_sources: 2, latest_verification: '2026-09-30T18:00:00Z' } }))
  await page.route('**/api/v1/auth/csrf/', route => route.fulfill({ json: { csrf_token: 'test-token' } }))
  await page.route(/\/api\/v1\/(saved-searches|alerts|external-opportunities)\//, async route => {
    const req = route.request(), path = new URL(req.url()).pathname, method = req.method(), body = req.postDataJSON()
    requests.push({ path, method, body })
    const list = (results: any[]) => ({ results, count: results.length, page: 1, page_size: 20 })
    if (path.includes('saved-searches')) {
      if (method === 'POST') { searches.push({ id: 1, ...body }); return route.fulfill({ status: 201, json: searches[0] }) }
      if (method === 'PATCH') { searches = searches.map(search => ({ ...search, ...body })); return route.fulfill({ json: searches[0] }) }
      if (method === 'DELETE') { searches = []; return route.fulfill({ status: 204 }) }
      return route.fulfill({ json: list(searches) })
    }
    if (path.includes('alerts')) {
      if (method === 'PUT') { read = true; return route.fulfill({ json: { id: 2, read_at: '2026-09-30' } }) }
      return route.fulfill({ json: list([{ id: 2, offer_id: 2, payload: { title: 'Stage finance' }, read_at: read ? '2026-09-30' : null }]) })
    }
    if (method === 'POST') { external = [{ id: 3, url: body.url, title: '', status: 'pending' }]; return route.fulfill({ status: 202, json: external[0] }) }
    return route.fulfill({ json: list(external) })
  })
  return requests
}

