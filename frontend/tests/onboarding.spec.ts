async function prepare(page: Page, initial = 'address', countries = ['FR', 'MA', 'GB', 'US', 'CI']) {
  let step = initial
  let address = { street_address: '', city: '', postal_code: '', district: '', region: '', country_code: '' }
  let eligibility = { citizenships: [] as string[], work_authorizations: [] as unknown[] }
  await page.route('**/api/v1/auth/me/', route => route.fulfill({ json: { user: { id: 1, username: 'ada', email: 'ada@example.test', onboarding_step: step } } }))
  await page.route('**/api/v1/auth/csrf/', route => route.fulfill({ json: { csrf_token: 'onboarding-csrf' } }))
  await page.route('**/api/v1/profile/', route => route.fulfill({ json: { current_resume_id: 42 } }))
  await page.route('**/api/v1/onboarding/', route => route.fulfill({ json: { step, address, ...eligibility, countries } }))
  await page.route('**/api/v1/onboarding/address/', async route => {
    expect(route.request().headers()['x-csrftoken']).toBe('onboarding-csrf')
    address = route.request().postDataJSON(); step = 'work-eligibility'
    await route.fulfill({ json: { step } })
  })
  await page.route('**/api/v1/onboarding/work-eligibility/', async route => {
    eligibility = route.request().postDataJSON(); step = 'complete'
    await route.fulfill({ json: { step } })
  })
}
